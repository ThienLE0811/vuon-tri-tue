async function main() {
  await connectDB();

  let count = 0;
  for (const ex of EXERCISES) {
    const lesson = await LessonModel.findOne({
      subjectId: ex.subjectId,
      grade: ex.grade,
      order: ex.order,
    }).lean();

    if (!lesson) {
      console.warn(
        `Skip: no lesson found for ${ex.subjectId} grade ${ex.grade} order ${ex.order}`
      );
      continue;
    }

    const extra = ALL_EXTRA_QUESTIONS.find(
      (e) => e.subjectId === ex.subjectId && e.grade === ex.grade && e.order === ex.order
    );
    const questions = extra ? [...ex.questions, ...extra.questions] : ex.questions;

    await ExerciseModel.updateOne(
      { lessonId: lesson._id },
      { $set: { lessonId: lesson._id, title: ex.title, questions } },
      { upsert: true }
    );
    count++;
  }

  console.log(`Seeded ${count} exercises.`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
